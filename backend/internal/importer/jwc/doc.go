// Package jwc 把学校教务处导出的课表聚合表（列表课程信息.xlsx）拆分为本系统
// 六类实体对应的规范 xlsx，交由现有 importer 的 preview/commit 流程落库。
//
// # 源表结构
//
// 教务处导出为单 sheet 聚合表，每行一个「周课表槽位」：同一门课、同一批行政班、
// 同一教室、同一星期/节次/起止周 的安排。共 29 列（中文表头）：
//
//	教学楼 上课教室 教室类型 楼层 星期 节次 起止周
//	课程序号 课程代码 课程名称 行政班 行政班个数
//	教师姓名 教师职称 教师工号 上课人数 人数上限 教室人数
//	开课学院 课程类别一 课程类别二 总学时 授课学时 已安排学时 周学时
//	年级 校区 学分 考核方式
//
// 关键语义：
//
//   - 课程序号：形如 113130004.68，唯一标识一个「开课」（一门课对一批行政班）。
//     同一课程序号可能跨多行（不同 星期/节次/起止周），教师也可能多行（合班上课）。
//   - 课程代码 + 行政班集合：与课程序号 1:1 对应。同 (课程代码, 行政班集合) 出现
//     ≥2 个课程序号即为「平行教学班」特例（同一门课拆成多套班并行开课），
//     本拆分器将其记入告警并跳过相关 offering/session，不臆测合并。
//   - 节次：区间 "3-4"/"1-4"/"9-10" 或单节 "1-1"/"2-2"，展开为逐节。
//   - 起止周：逗号分隔的段，每段为 [a-b] 或 a-b（区间）或 n（单周），可带 单/双
//     后缀做奇偶过滤（单=奇数周，双=偶数周）。例："[1-3]单,[4-6]双,[7-17]"。
//   - 行政班：逗号分隔；空串表示任选课（无固定行政班），跳过其 offering/session。
//
// # 六表映射
//
//  1. classrooms：按 上课教室 去重。name=上课教室, building=教学楼, capacity=教室人数,
//     type=教室类型映射后的英文键, floor=楼层, campus=校区, status=available。
//  2. catalog：按 课程代码 去重。name=课程名称, code=课程代码, credits=学分,
//     total_hours=总学时, category=课程类别二, exam_type=考核方式。
//  3. admin_classes：全局去重行政班。grade 由班名末位数字串前两位推导（241->2024）,
//     name=行政班名。
//  4. teaching_classes：按「行政班集合」键控的教学班。命名默认区间压缩（机电241~245），
//     超 64 字符回退「首班,次班等N班」并把完整成员写入 note。每个成员行政班一行
//     （父子扁平化，匹配 teaching_classes importer 契约）。
//  5. offerings：按 课程序号 去重。course=课程名称, teaching_class=合成教学班名,
//     semester=入参, teacher=教师名（合班按工号去重逗号合并）, course_seq=课程序号,
//     teacher_id/teacher_title/college/max_students/requirement/weekly_hours 同步。
//  6. sessions：周模式展开为具体日期课次。date=week1Monday+(week-1)*7+(weekday-1),
//     period_index=逐节, classroom=上课教室, course/teaching_class/semester 同上。
//
// # 展开与去重
//
// 合班上课（同一课程序号、同一槽位、不同教师）在按课程序号分组时自然合并为同一
// 槽位、教师集合并集，避免展开出重复 (教室,日期,节次) 课次。跨课程序号的同一槽位
// 属真实排课冲突，不在本层处理，留给 sessions importer 的 (教室+日期+节次) 唯一约束
// 与文件内去重报错。
//
// # 参数依赖
//
// Split 需要「学期标签」与「第一周周一」两个入参把周次换算成日期，并需要已加载的
// 作息制度列表预校验：展开出现的每个日期都要有 active regime，且 regime 含该节次，
// 否则视为未配置作息，返回错误不建任务（fail-fast，避免生成 6 个任务后才发现）。
//
// 详见各文件的中文注释。
